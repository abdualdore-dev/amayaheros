// Builds orders.html (the orders app) and runners.html (the runners app) from index.html (the staff app).
// orders.html shares the restaurant data (amaya/); runners.html keeps its own data under rnr/ in the same database.
// Both only switch the app mode, the name and the home-screen icon. Run after every change to index.html:
//   node scripts/build-orders.js          (write both)
//   node scripts/build-orders.js --check  (fail if either is out of date)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
function build(file, mode, swaps) {
  let h = src;
  const swap = (a, b) => { if (!h.includes(a)) throw new Error('build: anchor not found: ' + a); h = h.replace(a, b); };
  swap('<meta charset="UTF-8">', `<meta charset="UTF-8"><script>window.AMAYA_APP='${mode}'</script>`);
  swaps.forEach(([a, b]) => swap(a, b));
  h = h.replace('<!DOCTYPE html>', `<!DOCTYPE html>\n<!-- Generated from index.html by scripts/build-orders.js. Do not edit this file: edit index.html and run the script. -->`);
  const out = path.join(root, file);
  const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (process.argv.includes('--check')) { if (prev !== h) { console.error(file + ' is out of date: run node scripts/build-orders.js'); process.exitCode = 1; } else console.log(file + ' is up to date'); }
  else { fs.writeFileSync(out, h); console.log(file + ' written'); }
}
build('orders.html', 'orders', [
  ['<link rel="manifest" href="manifest.webmanifest">', '<link rel="manifest" href="orders.webmanifest">'],
  ['<link rel="apple-touch-icon" href="apple-touch-icon.png">', '<link rel="apple-touch-icon" href="orders-touch-icon.png"><meta name="apple-mobile-web-app-title" content="Amaya Orders">'],
  ['<link rel="icon" href="icon-192.png">', '<link rel="icon" href="orders-192.png">'],
  ['<title>Amaya Heroes</title>', '<title>Amaya Orders</title>'],
]);
build('runners.html', 'runners', [
  ['<link rel="manifest" href="manifest.webmanifest">', '<link rel="manifest" href="runners.webmanifest">'],
  ['<link rel="apple-touch-icon" href="apple-touch-icon.png">', '<link rel="apple-touch-icon" href="apple-touch-icon.png"><meta name="apple-mobile-web-app-title" content="Amaya Runners">'],
  ['<title>Amaya Heroes</title>', '<title>Amaya Runners</title>'],
]);
