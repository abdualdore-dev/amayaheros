// Builds orders.html (the orders app) from index.html (the staff app).
// Both apps share one code base and one database; orders.html only switches the app mode,
// its name and its home-screen icon. Run after every change to index.html:
//   node scripts/build-orders.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
let h = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const swap = (a, b) => { if (!h.includes(a)) throw new Error('build-orders: anchor not found: ' + a); h = h.replace(a, b); };
swap('<meta charset="UTF-8">', '<meta charset="UTF-8"><script>window.AMAYA_APP=\'orders\'</script>');
swap('<link rel="manifest" href="manifest.webmanifest">', '<link rel="manifest" href="orders.webmanifest">');
swap('<link rel="apple-touch-icon" href="apple-touch-icon.png">', '<link rel="apple-touch-icon" href="orders-touch-icon.png"><meta name="apple-mobile-web-app-title" content="Amaya Orders">');
swap('<link rel="icon" href="icon-192.png">', '<link rel="icon" href="orders-192.png">');
swap('<title>Amaya Heroes</title>', '<title>Amaya Orders</title>');
h = h.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated from index.html by scripts/build-orders.js. Do not edit this file: edit index.html and run the script. -->');
const out = path.join(root, 'orders.html');
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (process.argv.includes('--check')) { if (prev !== h) { console.error('orders.html is out of date: run node scripts/build-orders.js'); process.exit(1); } console.log('orders.html is up to date'); }
else { fs.writeFileSync(out, h); console.log('orders.html written'); }
